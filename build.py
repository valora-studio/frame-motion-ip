NBSP = [
    (re.compile(r"(\d) (\d{3})"), r"\1&nbsp;\2"),        # 3 000
    (re.compile(r"(\d) (₽|%|дн|рабоч|календ|банк|час|лет|мин|сек|кадр|ролик|круг)"), r"\1&nbsp;\2"),
    (re.compile(r" (—|–) "), r"&nbsp;\1 "),                  # тире не в начале строки
    (re.compile(r"(\d)–(\d)"), r"\1–&#8288;\2"),             # 2–4 не рвётся по тире
    (re.compile(r"(^|[\s>(«])([а-яёА-ЯЁ]{1,2}) (?=[^\s<])"), r"\1\2&nbsp;"),  # предлоги
]


def typo(html):
    """Неразрывные пробелы в тексте, но не внутри тегов."""
    parts = re.split(r"(<[^>]+>)", html)
    for i, part in enumerate(parts):
        if part.startswith("<"):
            continue
        for rx, rep in NBSP:
            part = rx.sub(rep, part)
        parts[i] = part
    return "".join(parts)



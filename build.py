def cap_html(text):
    words = text.split()
    out = []
    for w in words:
        if w.startswith("*") or "*" in w:
            w = re.sub(r"\*(.+?)\*", r"<em>\1</em>", w)
        out.append("<span>%s</span>" % w)
    return " ".join(out)


def wave(n=96, seed=7):
    """Звуковая дорожка: столбики разной высоты, детерминированно."""
    rnd = random.Random(seed)
    bars = []
    for i in range(n):
        h = 3 + abs(rnd.gauss(0, 1)) * 7 + (4 if i % 9 in (2, 3) else 0)
        h = min(h, 22)
        bars.append('<rect x="%d" y="%.1f" width="2" height="%.1f" rx="1"/>' % (i * 4, 12 - h / 2, h))
    return '<svg viewBox="0 0 %d 24" preserveAspectRatio="none">%s</svg>' % (n * 4, "".join(bars))


